//! Explicit electrical and thermal accounting for fusion-device and plant studies.
//!
//! This module deliberately keeps plasma/device gain separate from whole-plant
//! electrical gain. It is a transparent accounting layer, not a reactor model:
//! callers must supply measured or explicitly scenario-assumed power flows.
//!
//! A result is not a validated energy-gain claim unless all plant recirculating
//! loads are included and the inputs have traceable provenance.

use serde::{Deserialize, Serialize};

/// Inputs for one synchronized operating window.
///
/// All power values are average watts over the same interval and use the same
/// system boundary. The caller must not mix peak pulse power with time averages.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct PlantPowerBalanceInput {
    /// Fusion energy released as thermal power before blanket/heat-capture losses.
    pub fusion_thermal_power_w: f64,
    /// Energy delivered to the plasma or target by the primary driver.
    /// For magnetic confinement this is absorbed auxiliary heating; for LCF it
    /// is energy deposited in the target; for other concepts document the boundary.
    pub primary_energy_to_medium_w: f64,
    /// Electrical power drawn at the plant bus by the primary heating/driver system.
    pub primary_driver_wall_plug_power_w: f64,
    /// Fraction of fusion thermal power captured by the thermal conversion system.
    pub thermal_capture_fraction: f64,
    /// Thermal-to-electric conversion efficiency applied to captured heat.
    pub thermal_to_electric_efficiency: f64,
    /// Gross electrical output from a direct-conversion pathway, before plant auxiliary loads.
    pub direct_electric_output_w: f64,
    /// Magnet and power-supply electrical load.
    pub magnet_power_w: f64,
    /// Cryogenic electrical load.
    pub cryogenic_power_w: f64,
    /// Vacuum, pumping and exhaust-processing electrical load.
    pub vacuum_and_pumping_power_w: f64,
    /// Fuel-cycle, isotope separation and fuel-processing electrical load.
    pub fuel_cycle_power_w: f64,
    /// Coolant circulation and heat-rejection electrical load.
    pub cooling_and_heat_rejection_power_w: f64,
    /// Other balance-of-plant electrical loads.
    pub other_auxiliary_power_w: f64,
    /// True only when every material recirculating electrical load is included.
    ///
    /// If false, engineering gain and net export are withheld. This avoids
    /// presenting a partial auxiliary-load ledger as whole-plant performance.
    pub all_plant_auxiliaries_accounted_for: bool,
}

/// Auditable power-balance outputs for the supplied operating window.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct PlantPowerBalance {
    /// Fusion thermal power supplied by the caller.
    pub fusion_thermal_power_w: f64,
    /// Thermal power captured for conversion.
    pub captured_thermal_power_w: f64,
    /// Electricity generated from captured thermal power.
    pub thermal_electric_output_w: f64,
    /// Electricity generated by direct conversion.
    pub direct_electric_output_w: f64,
    /// Total gross electrical output before recirculating loads.
    pub gross_electric_output_w: f64,
    /// Sum of the supplied recirculating electrical loads.
    ///
    /// This is a complete plant value only when
    /// all_plant_auxiliaries_accounted_for was true.
    pub recirculating_electric_power_w: f64,
    /// Fusion power divided by energy delivered to the plasma or target.
    ///
    /// This is a device/primary-energy gain metric, not a whole-plant metric.
    pub primary_energy_gain: f64,
    /// Gross electrical output divided by recirculating electrical power.
    /// None when the auxiliary-load boundary is incomplete.
    pub engineering_electric_gain: Option<f64>,
    /// Net electrical export after recirculating loads.
    /// None when the auxiliary-load boundary is incomplete.
    pub net_electric_export_w: Option<f64>,
    /// Whether the supplied electrical boundary is complete.
    pub plant_boundary_complete: bool,
}

/// Validate and calculate a power balance without inventing missing loads.
pub fn calculate_plant_power_balance(
    input: &PlantPowerBalanceInput,
) -> Result<PlantPowerBalance, String> {
    let non_negative = [
        ("fusion_thermal_power_w", input.fusion_thermal_power_w),
        (
            "primary_driver_wall_plug_power_w",
            input.primary_driver_wall_plug_power_w,
        ),
        ("direct_electric_output_w", input.direct_electric_output_w),
        ("magnet_power_w", input.magnet_power_w),
        ("cryogenic_power_w", input.cryogenic_power_w),
        (
            "vacuum_and_pumping_power_w",
            input.vacuum_and_pumping_power_w,
        ),
        ("fuel_cycle_power_w", input.fuel_cycle_power_w),
        (
            "cooling_and_heat_rejection_power_w",
            input.cooling_and_heat_rejection_power_w,
        ),
        ("other_auxiliary_power_w", input.other_auxiliary_power_w),
    ];
    for (name, value) in non_negative {
        if !value.is_finite() {
            return Err(format!("{name} must be finite"));
        }
        if value < 0.0 {
            return Err(format!("{name} must be non-negative"));
        }
    }

    if !input.primary_energy_to_medium_w.is_finite() || input.primary_energy_to_medium_w <= 0.0 {
        return Err("primary_energy_to_medium_w must be finite and positive".to_string());
    }
    if !input.primary_driver_wall_plug_power_w.is_finite()
        || input.primary_driver_wall_plug_power_w <= 0.0
    {
        return Err("primary_driver_wall_plug_power_w must be finite and positive".to_string());
    }
    if !input.thermal_capture_fraction.is_finite()
        || !(0.0..=1.0).contains(&input.thermal_capture_fraction)
    {
        return Err("thermal_capture_fraction must be finite and in [0, 1]".to_string());
    }
    if !input.thermal_to_electric_efficiency.is_finite()
        || !(0.0..=1.0).contains(&input.thermal_to_electric_efficiency)
    {
        return Err("thermal_to_electric_efficiency must be finite and in [0, 1]".to_string());
    }

    let captured_thermal_power_w = input.fusion_thermal_power_w * input.thermal_capture_fraction;
    let thermal_electric_output_w = captured_thermal_power_w * input.thermal_to_electric_efficiency;
    let gross_electric_output_w = thermal_electric_output_w + input.direct_electric_output_w;

    let recirculating_electric_power_w = input.primary_driver_wall_plug_power_w
        + input.magnet_power_w
        + input.cryogenic_power_w
        + input.vacuum_and_pumping_power_w
        + input.fuel_cycle_power_w
        + input.cooling_and_heat_rejection_power_w
        + input.other_auxiliary_power_w;

    if !recirculating_electric_power_w.is_finite() || recirculating_electric_power_w <= 0.0 {
        return Err("recirculating electric power must be finite and positive".to_string());
    }

    let primary_energy_gain = input.fusion_thermal_power_w / input.primary_energy_to_medium_w;
    if !primary_energy_gain.is_finite() || !gross_electric_output_w.is_finite() {
        return Err("calculated power balance is not finite".to_string());
    }

    let (engineering_electric_gain, net_electric_export_w) =
        if input.all_plant_auxiliaries_accounted_for {
            (
                Some(gross_electric_output_w / recirculating_electric_power_w),
                Some(gross_electric_output_w - recirculating_electric_power_w),
            )
        } else {
            (None, None)
        };

    Ok(PlantPowerBalance {
        fusion_thermal_power_w: input.fusion_thermal_power_w,
        captured_thermal_power_w,
        thermal_electric_output_w,
        direct_electric_output_w: input.direct_electric_output_w,
        gross_electric_output_w,
        recirculating_electric_power_w,
        primary_energy_gain,
        engineering_electric_gain,
        net_electric_export_w,
        plant_boundary_complete: input.all_plant_auxiliaries_accounted_for,
    })
}

/// Inputs for a transparent first-order levelized-cost-of-electricity estimate.
///
/// This is a scenario model, not a bankable financial model. Annual replacement
/// costs must include the expected replacement/maintenance burden for the
/// assumed availability. Taxes, financing structure, decommissioning, grid
/// connection and storage should be included in the relevant annual cost inputs
/// before comparing scenarios.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct PlantEconomicsInput {
    /// Net electrical power delivered at the grid boundary, in watts.
    pub net_export_power_w: f64,
    /// Long-run fraction of calendar time the plant exports at the stated power.
    pub availability_fraction: f64,
    /// Overnight capital cost in USD.
    pub capital_cost_usd: f64,
    /// Annual fixed operation and maintenance costs in USD/year.
    pub annual_fixed_om_usd: f64,
    /// Annualized component replacement and major maintenance costs in USD/year.
    pub annual_replacement_cost_usd: f64,
    /// Variable operating costs in USD/MWh.
    pub variable_om_usd_per_mwh: f64,
    /// Fuel-cycle costs in USD/MWh.
    pub fuel_cost_usd_per_mwh: f64,
    /// Real discount rate as a fraction (for example 0.08 = 8%).
    pub real_discount_rate: f64,
    /// Economic plant life in years.
    pub lifetime_years: u32,
}

/// First-order LCOE output for a single declared scenario.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct PlantEconomicsResult {
    /// Capital recovery factor for the declared discount rate and life.
    pub capital_recovery_factor: f64,
    /// Annual net electricity exported, in MWh/year.
    pub annual_net_generation_mwh: f64,
    /// Annualized capital cost, in USD/year.
    pub annualized_capital_cost_usd: f64,
    /// Levelized cost of electricity, in USD/MWh.
    pub lcoe_usd_per_mwh: f64,
}

/// Calculate a first-order LCOE from positive net export and explicit cost inputs.
pub fn calculate_lcoe(input: &PlantEconomicsInput) -> Result<PlantEconomicsResult, String> {
    let non_negative = [
        ("capital_cost_usd", input.capital_cost_usd),
        ("annual_fixed_om_usd", input.annual_fixed_om_usd),
        (
            "annual_replacement_cost_usd",
            input.annual_replacement_cost_usd,
        ),
        ("variable_om_usd_per_mwh", input.variable_om_usd_per_mwh),
        ("fuel_cost_usd_per_mwh", input.fuel_cost_usd_per_mwh),
    ];
    for (name, value) in non_negative {
        if !value.is_finite() || value < 0.0 {
            return Err(format!("{name} must be finite and non-negative"));
        }
    }

    if !input.net_export_power_w.is_finite() || input.net_export_power_w <= 0.0 {
        return Err("net_export_power_w must be finite and positive".to_string());
    }
    if !input.availability_fraction.is_finite()
        || !(0.0..=1.0).contains(&input.availability_fraction)
        || input.availability_fraction == 0.0
    {
        return Err("availability_fraction must be finite and in (0, 1]".to_string());
    }
    if !input.real_discount_rate.is_finite() || !(0.0..1.0).contains(&input.real_discount_rate) {
        return Err("real_discount_rate must be finite and in [0, 1)".to_string());
    }
    if input.lifetime_years == 0 {
        return Err("lifetime_years must be positive".to_string());
    }

    let years = input.lifetime_years as f64;
    let capital_recovery_factor = if input.real_discount_rate == 0.0 {
        1.0 / years
    } else {
        let growth = (1.0 + input.real_discount_rate).powf(years);
        input.real_discount_rate * growth / (growth - 1.0)
    };

    let annual_net_generation_mwh =
        input.net_export_power_w / 1_000_000.0 * 8_760.0 * input.availability_fraction;
    let annualized_capital_cost_usd = input.capital_cost_usd * capital_recovery_factor;
    let annual_fixed_costs =
        annualized_capital_cost_usd + input.annual_fixed_om_usd + input.annual_replacement_cost_usd;
    let lcoe_usd_per_mwh = annual_fixed_costs / annual_net_generation_mwh
        + input.variable_om_usd_per_mwh
        + input.fuel_cost_usd_per_mwh;

    if !capital_recovery_factor.is_finite()
        || !annual_net_generation_mwh.is_finite()
        || !lcoe_usd_per_mwh.is_finite()
    {
        return Err("calculated LCOE is not finite".to_string());
    }

    Ok(PlantEconomicsResult {
        capital_recovery_factor,
        annual_net_generation_mwh,
        annualized_capital_cost_usd,
        lcoe_usd_per_mwh,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn complete_input() -> PlantPowerBalanceInput {
        PlantPowerBalanceInput {
            fusion_thermal_power_w: 1_000_000_000.0,
            primary_energy_to_medium_w: 50_000_000.0,
            primary_driver_wall_plug_power_w: 100_000_000.0,
            thermal_capture_fraction: 0.9,
            thermal_to_electric_efficiency: 0.4,
            direct_electric_output_w: 0.0,
            magnet_power_w: 20_000_000.0,
            cryogenic_power_w: 10_000_000.0,
            vacuum_and_pumping_power_w: 5_000_000.0,
            fuel_cycle_power_w: 10_000_000.0,
            cooling_and_heat_rejection_power_w: 15_000_000.0,
            other_auxiliary_power_w: 5_000_000.0,
            all_plant_auxiliaries_accounted_for: true,
        }
    }

    #[test]
    fn separates_primary_gain_from_whole_plant_gain() {
        let result = calculate_plant_power_balance(&complete_input()).unwrap();
        assert!((result.primary_energy_gain - 20.0).abs() < 1e-12);
        assert!((result.gross_electric_output_w - 360_000_000.0).abs() < 1.0);
        assert!((result.recirculating_electric_power_w - 165_000_000.0).abs() < 1.0);
        assert!((result.engineering_electric_gain.unwrap() - 360.0 / 165.0).abs() < 1e-12);
        assert!((result.net_electric_export_w.unwrap() - 195_000_000.0).abs() < 1.0);
    }

    #[test]
    fn incomplete_plant_boundary_withholds_engineering_claims() {
        let mut input = complete_input();
        input.all_plant_auxiliaries_accounted_for = false;
        let result = calculate_plant_power_balance(&input).unwrap();
        assert_eq!(result.engineering_electric_gain, None);
        assert_eq!(result.net_electric_export_w, None);
        assert!(!result.plant_boundary_complete);
    }

    #[test]
    fn direct_conversion_is_counted_as_gross_electricity() {
        let mut input = complete_input();
        input.direct_electric_output_w = 25_000_000.0;
        let result = calculate_plant_power_balance(&input).unwrap();
        assert!((result.gross_electric_output_w - 385_000_000.0).abs() < 1.0);
    }

    #[test]
    fn rejects_non_finite_and_invalid_efficiencies() {
        let mut input = complete_input();
        input.thermal_capture_fraction = f64::NAN;
        assert!(calculate_plant_power_balance(&input).is_err());

        let mut input = complete_input();
        input.thermal_to_electric_efficiency = 1.1;
        assert!(calculate_plant_power_balance(&input).is_err());

        let mut input = complete_input();
        input.primary_energy_to_medium_w = 0.0;
        assert!(calculate_plant_power_balance(&input).is_err());
    }

    #[test]
    fn lcoe_includes_availability_and_replacement_cost() {
        let input = PlantEconomicsInput {
            net_export_power_w: 150_000_000.0,
            availability_fraction: 0.85,
            capital_cost_usd: 10_000_000_000.0,
            annual_fixed_om_usd: 250_000_000.0,
            annual_replacement_cost_usd: 100_000_000.0,
            variable_om_usd_per_mwh: 15.0,
            fuel_cost_usd_per_mwh: 5.0,
            real_discount_rate: 0.08,
            lifetime_years: 30,
        };
        let result = calculate_lcoe(&input).unwrap();
        assert!(result.annual_net_generation_mwh > 1_000_000.0);
        assert!(result.lcoe_usd_per_mwh > 20.0);
        assert!(result.lcoe_usd_per_mwh.is_finite());
    }

    #[test]
    fn lcoe_zero_discount_rate_uses_linear_capital_recovery() {
        let input = PlantEconomicsInput {
            net_export_power_w: 1_000_000.0,
            availability_fraction: 1.0,
            capital_cost_usd: 100.0,
            annual_fixed_om_usd: 0.0,
            annual_replacement_cost_usd: 0.0,
            variable_om_usd_per_mwh: 0.0,
            fuel_cost_usd_per_mwh: 0.0,
            real_discount_rate: 0.0,
            lifetime_years: 20,
        };
        let result = calculate_lcoe(&input).unwrap();
        assert!((result.capital_recovery_factor - 0.05).abs() < 1e-12);
    }

    #[test]
    fn lcoe_rejects_no_net_export() {
        let input = PlantEconomicsInput {
            net_export_power_w: 0.0,
            availability_fraction: 0.9,
            capital_cost_usd: 1.0,
            annual_fixed_om_usd: 0.0,
            annual_replacement_cost_usd: 0.0,
            variable_om_usd_per_mwh: 0.0,
            fuel_cost_usd_per_mwh: 0.0,
            real_discount_rate: 0.05,
            lifetime_years: 20,
        };
        assert!(calculate_lcoe(&input).is_err());
    }
}
